  static void showLanguageSelectorModal(BuildContext context, String currentLang, Function(String) onSelect) {
    showModalBottomSheet(
      context: context,
      shape: const RoundedRectangleBorder(
        borderRadius: BorderRadius.vertical(top: Radius.circular(20)),
      ),
      backgroundColor: Colors.white,
      builder: (ctx) {
        return SafeArea(
          child: Padding(
            padding: const EdgeInsets.symmetric(horizontal: 20, vertical: 16),
            child: Column(
              mainAxisSize: MainAxisSize.min,
              crossAxisAlignment: CrossAxisAlignment.start,
              children: [
                Row(
                  children: [
                    const Icon(Icons.translate_rounded, color: Color(0xFF059669), size: 22),
                    const SizedBox(width: 8),
                    const Expanded(
                      child: Text(
                        "Select Language / भाषा चुनें",
                        style: TextStyle(fontSize: 15.5, fontWeight: FontWeight.bold, color: Color(0xFF0F172A)),
                        overflow: TextOverflow.ellipsis,
                      ),
                    ),
                    IconButton(
                      icon: const Icon(Icons.close_rounded, size: 20, color: Color(0xFF64748B)),
                      onPressed: () => Navigator.pop(ctx),
                    ),
                  ],
                ),
                const SizedBox(height: 12),
                ...supportedLanguages.map((lang) {
                  final isSelected = currentLang == lang["code"];
                  return Material(
                    color: Colors.transparent,
                    child: Container(
                      margin: const EdgeInsets.only(bottom: 8),
                      decoration: BoxDecoration(
                        color: isSelected ? const Color(0xFFECFDF5) : Colors.white,
                        borderRadius: BorderRadius.circular(12),
                        border: Border.all(
                          color: isSelected ? const Color(0xFF059669) : const Color(0xFFE2E8F0),
                          width: isSelected ? 1.5 : 1.0,
                        ),
                      ),
                      child: ListTile(
                        leading: Text(
                          lang["flag"] ?? "🌐",
                          style: const TextStyle(fontSize: 22),
                        ),
                        title: Text(
                          lang["native"] ?? "",
                          style: TextStyle(
                            fontSize: 15,
                            fontWeight: isSelected ? FontWeight.bold : FontWeight.w600,
                            color: isSelected ? const Color(0xFF065F46) : const Color(0xFF1E293B),
                          ),
                        ),
                        subtitle: Text(
                          lang["name"] ?? "",
                          style: const TextStyle(fontSize: 12, color: Color(0xFF64748B)),
                        ),
                        trailing: isSelected
                            ? const Icon(Icons.check_circle_rounded, color: Color(0xFF059669))
                            : null,
                        onTap: () {
                          onSelect(lang["code"] ?? "en");
                          Navigator.pop(ctx);
                        },
                      ),
                    ),
                  );
                }),
                const SizedBox(height: 8),
              ],
            ),
          ),
        );
      },
    );
  }

  static String getLanguageName(String code) {
    final match = supportedLanguages.firstWhere(
      (l) => l["code"] == code,
      orElse: () => {"native": code},
    );
    return match["native"] ?? code;
  }
